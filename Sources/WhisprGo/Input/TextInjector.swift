import AppKit
import ApplicationServices
import CoreGraphics
import Foundation

enum SyntheticEventTag {
    // ASCII "WHISPRGO". The global hotkey tap lets these events pass through
    // without interpreting WhisprGo's own Cmd-V as a configured shortcut.
    static let pasteCommand: Int64 = 0x5748_4953_5052_474F
}

@MainActor
enum TextInjector {
    private static let webAreaRole = "AXWebArea"
    private static let editableRoles: Set<String> = [
        kAXTextFieldRole,
        kAXTextAreaRole,
        kAXComboBoxRole,
    ]
    private static let pasteEventDelay = Duration.milliseconds(5)
    private static let pasteboardRestoreDelay = Duration.seconds(1)
    static let pasteSessionType = NSPasteboard.PasteboardType(
        "com.whisprgo.app.PasteSession"
    )
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let transientType = NSPasteboard.PasteboardType(
        "org.nspasteboard.TransientType"
    )
    private static let autoGeneratedType = NSPasteboard.PasteboardType(
        "org.nspasteboard.AutoGeneratedType"
    )
    private static var pendingPasteboardRestore: PendingPasteboardRestore?
    private static var pasteboardRestoreTask: Task<Void, Never>?
    private static let richEditorBundleIDs: Set<String> = [
        "com.apple.mail",
        "com.microsoft.outlook",
        "com.mimestream.mimestream",
        "com.readdle.smartemail-macos",
        "io.canarymail.mac",
    ]

    struct Target {
        /// The focused text element at recording start. Nil when the app
        /// does not expose one; delivery then relies on Command-V.
        let element: AXUIElement?
        let processIdentifier: pid_t
        let applicationName: String?
        let prefersPaste: Bool
    }

    /// Why a transcript was left on the clipboard instead of being typed.
    enum CopyReason: Equatable {
        case accessibilityMissing
        case noTarget
        case targetChanged
        case pasteFailed
    }

    /// Every delivery ends in exactly one of these, and each one is shown to
    /// the user so they always know where the text went.
    enum Result: Equatable {
        /// Written into the captured text field through Accessibility.
        case inserted(appName: String?)
        /// Pasted with Command-V into the app that was dictated into.
        case pasted(appName: String?)
        /// Left on the clipboard for a manual Command-V.
        case copied(CopyReason)
        case ignored
        case failed(String)

        var errorMessage: String? {
            guard case let .failed(message) = self else { return nil }
            return message
        }

        var isManualPaste: Bool {
            if case .copied = self { return true }
            return false
        }

        /// One short line for the on-screen notice.
        var notice: String? {
            switch self {
            case let .inserted(name):
                return name.map { "Inserted into \($0)" } ?? "Inserted"
            case let .pasted(name):
                return name.map { "Pasted into \($0)" } ?? "Pasted"
            case .copied(.accessibilityMissing):
                return "Copied · Allow Accessibility to paste automatically"
            case .copied(.noTarget):
                return "Copied · No text field was focused · Press ⌘V"
            case .copied(.targetChanged):
                return "Copied · You switched apps · Press ⌘V"
            case .copied(.pasteFailed):
                return "Copied · Automatic paste failed · Press ⌘V"
            case .ignored:
                return nil
            case let .failed(message):
                return message
            }
        }
    }

    /// Capturing the destination before recording prevents transient call and
    /// screen-sharing controls from stealing the insertion target while the
    /// transcript is being produced.
    static func captureTarget() -> Target? {
        let ownProcess = ProcessInfo.processInfo.processIdentifier
        let frontmost = NSWorkspace.shared.frontmostApplication
            .flatMap { $0.processIdentifier == ownProcess ? nil : $0 }

        guard AXIsProcessTrusted() else {
            return frontmost.map {
                Target(
                    element: nil,
                    processIdentifier: $0.processIdentifier,
                    applicationName: $0.localizedName,
                    prefersPaste: true
                )
            }
        }

        let system = AXUIElementCreateSystemWide()
        var focusedValue: CFTypeRef?
        let lookup = AXUIElementCopyAttributeValue(
            system,
            kAXFocusedUIElementAttribute as CFString,
            &focusedValue
        )
        var processIdentifier: pid_t = 0
        guard lookup == .success,
              let focusedValue,
              CFGetTypeID(focusedValue) == AXUIElementGetTypeID(),
              AXUIElementGetPid(focusedValue as! AXUIElement, &processIdentifier) == .success,
              // WhisprGo's own text fields (Settings) are valid targets; its
              // buttons and menu-bar panel are not.
              processIdentifier != ownProcess
                || editableRoles.contains(stringAttribute(focusedValue as! AXUIElement, kAXRoleAttribute) ?? "")
        else {
            // Some apps never expose a focused element. Command-V into the
            // same frontmost app is still the right delivery for them.
            return frontmost.map {
                Target(
                    element: nil,
                    processIdentifier: $0.processIdentifier,
                    applicationName: $0.localizedName,
                    prefersPaste: true
                )
            }
        }

        let focused = focusedValue as! AXUIElement
        let application = NSRunningApplication(processIdentifier: processIdentifier)
        let bundleIdentifier = application?.bundleIdentifier?.lowercased()
        let role = stringAttribute(focused, kAXRoleAttribute)
        let isKnownRichEditor = role == kAXTextAreaRole
            && bundleIdentifier.map(richEditorBundleIDs.contains) == true
        return Target(
            element: focused,
            processIdentifier: processIdentifier,
            applicationName: application?.localizedName,
            prefersPaste: isKnownRichEditor || isInsideWebContent(focused)
        )
    }

    /// Delivers a transcript. Types it into the captured field when possible,
    /// pastes it into the same app when that app is still in front, and
    /// otherwise leaves it on the clipboard. It never brings another app to
    /// the front, so a transcript cannot land somewhere the user did not see.
    static func inject(_ text: String, into capturedTarget: Target? = nil) async -> Result {
        guard !text.isEmpty else { return .ignored }
        guard AXIsProcessTrusted() else {
            return copyForManualPaste(text, reason: .accessibilityMissing)
        }

        guard let target = capturedTarget ?? captureTarget() else {
            return copyForManualPaste(text, reason: .noTarget)
        }
        if let element = target.element,
           !target.prefersPaste,
           insertDirectly(text, into: element) {
            return .inserted(appName: target.applicationName)
        }

        if let reason = pasteDecision(
            targetProcess: target.processIdentifier,
            frontmostProcess: NSWorkspace.shared.frontmostApplication?.processIdentifier
        ) {
            return copyForManualPaste(text, reason: reason)
        }
        return await paste(text, into: target)
    }

    /// Command-V only goes to the app the user dictated into, and only while
    /// it is still in front.
    static func pasteDecision(
        targetProcess: pid_t,
        frontmostProcess: pid_t?
    ) -> CopyReason? {
        frontmostProcess == targetProcess ? nil : .targetChanged
    }

    /// Puts the transcript on the clipboard and leaves it there.
    private static func copyForManualPaste(_ text: String, reason: CopyReason) -> Result {
        let pasteboard = NSPasteboard.general
        restorePendingPasteboardIfOwned(on: pasteboard)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let bundleIdentifier = Bundle.main.bundleIdentifier {
            item.setString(bundleIdentifier, forType: sourceType)
        }
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            return .failed("The transcript could not be copied. It is saved in History.")
        }
        return .copied(reason)
    }

    private static func paste(_ text: String, into target: Target) async -> Result {
        let pasteboard = NSPasteboard.general
        restorePendingPasteboardIfOwned(on: pasteboard)
        let snapshot = PasteboardSnapshot(pasteboard: pasteboard)
        let sessionID = UUID().uuidString
        let pasteboardItem = NSPasteboardItem()
        pasteboardItem.setString(text, forType: .string)
        pasteboardItem.setString(sessionID, forType: pasteSessionType)
        pasteboardItem.setData(Data(), forType: transientType)
        pasteboardItem.setData(Data(), forType: autoGeneratedType)
        if let bundleIdentifier = Bundle.main.bundleIdentifier {
            pasteboardItem.setString(bundleIdentifier, forType: sourceType)
        }

        pasteboard.clearContents()
        guard pasteboard.writeObjects([pasteboardItem]),
              pasteboard.string(forType: .string) == text
        else {
            snapshot.restore(on: pasteboard)
            return .failed("Text could not be copied for automatic insertion.")
        }
        let ownedChangeCount = pasteboard.changeCount

        if let element = target.element {
            _ = AXUIElementSetAttributeValue(
                element,
                kAXFocusedAttribute as CFString,
                kCFBooleanTrue
            )
            // WebKit and Chromium commit focus asynchronously after their
            // editor is refocused.
            try? await Task.sleep(for: .milliseconds(16))
        }

        guard await postPasteCommand() else {
            // Keep the transcript on the clipboard for a manual paste.
            return copyForManualPaste(text, reason: .pasteFailed)
        }

        // Accessibility values in Chromium, WebKit, and rich editors can lag or
        // omit successful edits. Treat posting the paste command as delivery
        // instead of producing a false error from an unreliable AX read-back.
        // The one-second ownership window covers editors that consume Cmd-V
        // asynchronously and does not extend the latency-sensitive path.
        schedulePasteboardRestore(
            snapshot,
            on: pasteboard,
            expectedChangeCount: ownedChangeCount,
            text: text,
            sessionID: sessionID
        )
        return .pasted(appName: target.applicationName)
    }

    private static func restorePendingPasteboardIfOwned(on pasteboard: NSPasteboard) {
        pasteboardRestoreTask?.cancel()
        pasteboardRestoreTask = nil
        guard let pendingPasteboardRestore else { return }
        Self.pendingPasteboardRestore = nil
        guard pasteboardIsOwned(
            pasteboard,
            expectedChangeCount: pendingPasteboardRestore.expectedChangeCount,
            text: pendingPasteboardRestore.text,
            sessionID: pendingPasteboardRestore.sessionID
        ) else { return }
        pendingPasteboardRestore.snapshot.restore(on: pasteboard)
    }

    private static func schedulePasteboardRestore(
        _ snapshot: PasteboardSnapshot,
        on pasteboard: NSPasteboard,
        expectedChangeCount: Int,
        text: String,
        sessionID: String
    ) {
        pendingPasteboardRestore = PendingPasteboardRestore(
            snapshot: snapshot,
            expectedChangeCount: expectedChangeCount,
            text: text,
            sessionID: sessionID
        )
        pasteboardRestoreTask = Task { @MainActor in
            do {
                try await Task.sleep(for: pasteboardRestoreDelay)
            } catch {
                return
            }
            guard let pendingPasteboardRestore,
                  pendingPasteboardRestore.sessionID == sessionID
            else { return }
            Self.pendingPasteboardRestore = nil
            pasteboardRestoreTask = nil
            guard pasteboardIsOwned(
                pasteboard,
                expectedChangeCount: expectedChangeCount,
                text: text,
                sessionID: sessionID
            ) else { return }
            snapshot.restore(on: pasteboard)
        }
    }

    static func pasteboardIsOwned(
        _ pasteboard: NSPasteboard,
        expectedChangeCount: Int,
        text: String,
        sessionID: String
    ) -> Bool {
        if pasteboard.changeCount == expectedChangeCount { return true }
        guard pasteboard.string(forType: .string) == text else { return false }
        let currentSessionID = pasteboard.string(forType: pasteSessionType)
        return currentSessionID == nil || currentSessionID == sessionID
    }

    private static func insertDirectly(_ text: String, into element: AXUIElement) -> Bool {
        let valueBefore = stringAttribute(element, kAXValueAttribute)
        let selectedRange = rangeAttribute(element, kAXSelectedTextRangeAttribute)
        guard AXUIElementSetAttributeValue(
            element,
            kAXSelectedTextAttribute as CFString,
            text as CFString
        ) == .success else { return false }

        guard let valueBefore else {
            // Native controls occasionally expose a writable selection without
            // exposing their full value. Web controls never take this branch.
            return true
        }
        guard let valueAfter = stringAttribute(element, kAXValueAttribute) else {
            return false
        }
        if let selectedRange,
           let expected = replacing(valueBefore, range: selectedRange, with: text) {
            return valueAfter == expected || valueAfter != valueBefore
        }
        return valueAfter != valueBefore
    }

    private static func isInsideWebContent(_ element: AXUIElement) -> Bool {
        var current: AXUIElement? = element
        for _ in 0..<10 {
            guard let candidate = current else { break }
            if stringAttribute(candidate, kAXRoleAttribute) == webAreaRole {
                return true
            }
            current = elementAttribute(candidate, kAXParentAttribute)
        }
        return false
    }

    static func replacing(
        _ value: String,
        range: CFRange,
        with replacement: String
    ) -> String? {
        let source = value as NSString
        guard range.location >= 0,
              range.length >= 0,
              range.location <= source.length,
              range.location + range.length <= source.length
        else { return nil }
        return source.replacingCharacters(
            in: NSRange(location: range.location, length: range.length),
            with: replacement
        )
    }

    private static func stringAttribute(
        _ element: AXUIElement,
        _ attribute: String
    ) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            element,
            attribute as CFString,
            &value
        ) == .success, let value else { return nil }
        if let string = value as? String { return string }
        return (value as? NSAttributedString)?.string
    }

    private static func rangeAttribute(
        _ element: AXUIElement,
        _ attribute: String
    ) -> CFRange? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            element,
            attribute as CFString,
            &value
        ) == .success,
              let value,
              CFGetTypeID(value) == AXValueGetTypeID()
        else { return nil }
        var range = CFRange()
        guard AXValueGetValue(value as! AXValue, .cfRange, &range) else { return nil }
        return range
    }

    private static func elementAttribute(
        _ element: AXUIElement,
        _ attribute: String
    ) -> AXUIElement? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            element,
            attribute as CFString,
            &value
        ) == .success,
              let value,
              CFGetTypeID(value) == AXUIElementGetTypeID()
        else { return nil }
        return (value as! AXUIElement)
    }

    private static func postPasteCommand() async -> Bool {
        guard let source = CGEventSource(stateID: .privateState),
              let commandDown = CGEvent(
                  keyboardEventSource: source,
                  virtualKey: 55,
                  keyDown: true
              ),
              let keyDown = CGEvent(
                  keyboardEventSource: source,
                  virtualKey: 9,
                  keyDown: true
              ),
              let keyUp = CGEvent(
                  keyboardEventSource: source,
                  virtualKey: 9,
                  keyDown: false
              ),
              let commandUp = CGEvent(
                  keyboardEventSource: source,
                  virtualKey: 55,
                  keyDown: false
              ) else {
            return false
        }

        commandDown.flags = .maskCommand
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        for event in [commandDown, keyDown, keyUp, commandUp] {
            event.setIntegerValueField(
                .eventSourceUserData,
                value: SyntheticEventTag.pasteCommand
            )
        }
        commandDown.post(tap: .cghidEventTap)
        try? await Task.sleep(for: pasteEventDelay)
        keyDown.post(tap: .cghidEventTap)
        try? await Task.sleep(for: pasteEventDelay)
        keyUp.post(tap: .cghidEventTap)
        try? await Task.sleep(for: pasteEventDelay)
        commandUp.post(tap: .cghidEventTap)
        return true
    }

    private struct PendingPasteboardRestore {
        let snapshot: PasteboardSnapshot
        let expectedChangeCount: Int
        let text: String
        let sessionID: String
    }

    struct PasteboardSnapshot {
        struct Item {
            struct Representation {
                let type: NSPasteboard.PasteboardType
                let data: Data
            }

            let representations: [Representation]
        }

        let items: [Item]

        init(pasteboard: NSPasteboard) {
            items = (pasteboard.pasteboardItems ?? []).compactMap { pasteboardItem in
                let representations = pasteboardItem.types.compactMap { type -> Item.Representation? in
                    guard let data = pasteboardItem.data(forType: type) else { return nil }
                    return Item.Representation(type: type, data: data)
                }
                return representations.isEmpty ? nil : Item(representations: representations)
            }
        }

        @discardableResult
        func restore(
            on pasteboard: NSPasteboard,
            ifChangeCountIs expectedChangeCount: Int? = nil
        ) -> Bool {
            if let expectedChangeCount, pasteboard.changeCount != expectedChangeCount {
                return false
            }

            pasteboard.clearContents()
            guard !items.isEmpty else { return true }

            let restoredItems = items.map { item -> NSPasteboardItem in
                let restoredItem = NSPasteboardItem()
                for representation in item.representations {
                    restoredItem.setData(representation.data, forType: representation.type)
                }
                return restoredItem
            }
            return pasteboard.writeObjects(restoredItems)
        }
    }
}
